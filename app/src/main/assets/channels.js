function decadeClause(y) {
  // Exact year words (1990 OR 1991 ...) instead of a wildcard: same results, about 10x faster.
  const years = Array.from({ length: 10 }, (_, i) => y + i).join(' OR ');
  return ` AND (year:[${y} TO ${y + 9}] OR subject:${y}s OR subject:"${String(y).slice(2)}s" OR title:(${years}))`;
}

function lineup(decId) {
  const d = DECADES.find(x => x.id === decId) || DECADES.find(x => x.id === DEFAULT_DECADE);
  const avail = (typeof window !== 'undefined' && window.AVAIL && window.AVAIL[d.id]) || null;
  const allAvail = (typeof window !== 'undefined' && window.AVAIL && window.AVAIL.all) || {};
  const baseKeys = LINEUPS[d.id].filter(k => !SHOWS[k] || SHOWS[k][d.id]).filter(k => !DROPPED.has(k));
  let keys = avail ? baseKeys.filter(k => ((THEMES[k].allYears ? allAvail[k] : avail[k]) || 0) >= 10) : baseKeys;
  // A decade still being checked: keep the full dial (unchecked channels use live search).
  if (keys.length < 10) keys = baseKeys.filter(k => THEMES[k].allYears || !avail || !(k in avail) || avail[k] >= 10);
  const chans = keys.map(key => {
    const t = THEMES[key];
    // allYears channels (the hardcore channel) pull from every decade and share one schedule on every tab.
    const shows = SHOWS[key] && SHOWS[key][d.id];
    if (shows) return { key: d.id + ':' + key, dec: d.id, call: t.call, name: t.name, color: t.color, adult: false, shows,
                        q: showQuery(shows.slice(0, 12)), qs: [showQuery(shows.slice(0, 13)), showQuery(shows.slice(13))].filter(q => q !== '()') };
    return { key: (t.allYears ? 'all' : d.id) + ':' + key, dec: d.id, call: t.call, name: t.name, color: t.color, adult: !!t.adult,
             q: '(' + t.q + ')' + (t.allYears ? '' : decadeClause(d.y)) + (t.adult ? NO_MINORS + NO_GAY : '') };
  });
  // Two special channels on every tab, just before the late-night adult ones.
  const at = chans.findIndex(c => c.adult);
  chans.splice(at < 0 ? chans.length : at, 0,
    { key: d.id + ':prevue', dec: d.id, call: 'GUIDE', name: 'Prevue Guide', color: '#7a5cff', special: 'prevue', q: '' },
    { key: d.id + ':local', dec: d.id, call: 'LOCAL', name: 'Local on the 8s', color: '#40c4ff', special: 'local', q: '' });
  chans.forEach((c, i) => { c.num = i + 1; });
  return chans;
}
